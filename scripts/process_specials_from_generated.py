def remove_white_background(img: Image.Image, threshold: int = 240) -> Image.Image:
    """
    Convert white/near-white background pixels to transparent.
    Works on images that have a checkerboard (already RGBA) or white background.
    """
    rgba = img.convert("RGBA")
    arr = np.array(rgba, dtype=np.uint8)
    
    r, g, b, a = arr[:,:,0], arr[:,:,1], arr[:,:,2], arr[:,:,3]
    
    # Detect white/near-white pixels (for white BG) or already-transparent areas
    # White background: R, G, B all high and similar
    is_white = (r.astype(int) >= threshold) & (g.astype(int) >= threshold) & (b.astype(int) >= threshold)
    
    # Also detect checkerboard pattern (light/dark grey squares)
    # Checkerboard: pixels alternate between ~(200,200,200) and ~(150,150,150)
    is_grey_checker = (
        (np.abs(r.astype(int) - g.astype(int)) < 10) &
        (np.abs(g.astype(int) - b.astype(int)) < 10) &
        (r.astype(int) > 140) & (r.astype(int) < 230) &
        (a == 255)  # fully opaque grey
    )
    
    bg_mask = is_white | is_grey_checker
    
    # Set background pixels to transparent
    new_alpha = np.where(bg_mask, 0, arr[:,:,3])
    
    # Soft anti-aliasing: pixels near the boundary get partial alpha
    # Apply simple flood-fill-ish erosion: dilate the foreground mask
    from scipy import ndimage
    fg_mask = ~bg_mask
    fg_dilated = ndimage.binary_dilation(fg_mask, iterations=2)
    edge_mask = fg_dilated & bg_mask
    
    # Give edge pixels a softer alpha based on proximity to foreground
    dist_to_fg = ndimage.distance_transform_edt(~fg_mask)
    edge_alpha = np.clip(1.0 - (dist_to_fg / 3.0), 0.0, 1.0) * 255
    new_alpha = np.where(edge_mask, edge_alpha.astype(np.uint8), new_alpha)
    
    result = arr.copy()
    result[:,:,3] = new_alpha.astype(np.uint8)
    return Image.fromarray(result, 'RGBA')


def remove_checkerboard_background(img: Image.Image) -> Image.Image:
    """
    Remove checkerboard (light-grey/medium-grey) background pattern.
    For images that come with transparency from the generator (RGBA PNGs with checkerboard preview).
    """
    rgba = img.convert("RGBA")
    arr = np.array(rgba, dtype=np.uint8)
    
    # If the image already has transparent regions (alpha < 200), preserve them
    has_transparency = arr[:,:,3].min() < 200
    if has_transparency:
        # Image already has proper transparency — just ensure corners are clean
        # Flood fill from corners to remove any leftover edge artifacts
        return rgba
    
    # Otherwise treat as white-bg image
    return remove_white_background(img, threshold=235)


def normalize_to_512(char_img: Image.Image, target_height: int = 454, grounding_y: int = 494) -> Image.Image:
    """Normalize a character illustration to 512x512 with consistent grounding."""
    arr = np.array(char_img.convert("RGBA"))
    alpha = arr[:, :, 3]
    
    ys, xs = np.where(alpha > 15)
    if len(ys) == 0:
        return char_img.resize((512, 512), Image.LANCZOS)
    
    # Crop to character
    y1, y2 = int(ys.min()), int(ys.max())
    x1, x2 = int(xs.min()), int(xs.max())
    cropped = char_img.crop((x1, y1, x2 + 1, y2 + 1))
    
    # Scale so character height = target_height
    scale = target_height / float(cropped.height)
    new_w = max(1, int(cropped.width * scale))
    new_h = max(1, int(cropped.height * scale))
    resized = cropped.resize((new_w, new_h), Image.LANCZOS)
    
    # Compose onto 512x512 transparent canvas
    canvas = Image.new("RGBA", (512, 512), (0, 0, 0, 0))
    paste_x = (512 - new_w) // 2
    paste_y = grounding_y - new_h
    canvas.paste(resized, (paste_x, paste_y), resized)
    return canvas


def process_generated(state: str, source_path: Path, target_path: Path, grounding_y: int = 494):
    """Full pipeline: load → remove BG → normalize → save."""
    print(f"\n  Processing {state} from {source_path.name}...")
    
    src = Image.open(source_path)
    print(f"    Source: {src.size} {src.mode}")
    
    # Step 1: Remove background
    if src.mode == "RGBA" and src.size[0] == 512 and src.size[1] == 512:
        # Already processed, just validate
        clean = src
    else:
        # Check if it has white or checkerboard background
        arr = np.array(src.convert("RGBA"))
        corner_colors = [arr[0,0,:3], arr[0,-1,:3], arr[-1,0,:3], arr[-1,-1,:3]]
        avg_corner = np.mean(corner_colors, axis=0)
        
        if all(c > 220 for c in avg_corner[:3]):
            # White background
            clean = remove_white_background(src, threshold=230)
        elif all(120 < c < 220 for c in avg_corner[:3]):
            # Checkerboard grey background
            clean = remove_checkerboard_background(src)
        else:
            # Already transparent or dark
            clean = src.convert("RGBA")
    
    # Step 2: Normalize to 512x512
    normalized = normalize_to_512(clean, target_height=454, grounding_y=grounding_y)
    
    # Step 3: Validate
    arr = np.array(normalized)
    alpha = arr[:, :, 3]
    corners = [int(alpha[0,0]), int(alpha[0,-1]), int(alpha[-1,0]), int(alpha[-1,-1])]
    ys, xs = np.where(alpha > 20)
    
    if len(ys) > 0:
        bbox = (int(xs.min()), int(ys.min()), int(xs.max()), int(ys.max()))
        height = int(ys.max() - ys.min())
    else:
        bbox = None
        height = 0
    
    print(f"    Output: 512x512 RGBA | BBox: {bbox} | Height: {height} | Corners: {corners}")
    
    if any(c > 0 for c in corners):
        print(f"    WARNING: Non-zero corner alpha detected: {corners}")
    
    # Step 4: Save
    target_path.parent.mkdir(parents=True, exist_ok=True)
    normalized.save(target_path, "PNG")
    print(f"    SAVED: {target_path}")
    
    return normalized


def create_proximity_hover_review(prox: Image.Image, hover: Image.Image):
    """Phase D: Create side-by-side PROXIMITY vs HOVER QA review sheet."""
    card_w, card_h = 480, 600
    sheet_w = card_w * 2 + 60
    sheet_h = card_h + 100

    sheet = Image.new("RGBA", (sheet_w, sheet_h), (22, 25, 38, 255))
    draw = ImageDraw.Draw(sheet)

    # Title banner
    draw.rectangle([0, 0, sheet_w, 70], fill=(35, 38, 55, 255))
    draw.text((20, 15), "MELI SPECIAL PERFORMANCE — PHASE D QA REVIEW", fill=(220, 225, 245, 255))
    draw.text((20, 40), "PROXIMITY (LEFT)  vs  HOVER (RIGHT)  |  512x512 RGBA  |  Phase C Rebuild", fill=(140, 150, 190, 255))

    items = [
        (prox, "PROXIMITY", "QUIET CURSOR AWARENESS", '"Oh... I noticed you."', (180, 100, 140)),
        (hover, "HOVER", "ACTIVE PLAYFUL ENGAGEMENT", '"Ehehe... you\'re right here!"', (100, 200, 140)),
    ]

    for idx, (img, name, intent, quote, accent_color) in enumerate(items):
        x0 = 20 + idx * (card_w + 20)
        y0 = 80

        # Card background
        draw.rounded_rectangle([x0, y0, x0 + card_w, y0 + card_h], radius=12,
                                fill=(30, 33, 50, 255), outline=(50, 55, 80, 255), width=2)

        # Checkerboard sprite area
        sprite_y = y0 + 10
        sprite_h = 400
        for cy in range(sprite_y, sprite_y + sprite_h, 18):
            for cx in range(x0 + 10, x0 + card_w - 10, 18):
                col = (42, 45, 62, 255) if ((cx//18 + cy//18) % 2 == 0) else (35, 38, 55, 255)
                draw.rectangle([cx, cy, cx+18, cy+18], fill=col)

        # Grounding line
        scale = sprite_h / 512.0
        gy = int(sprite_y + 494 * scale)
        draw.line([x0 + 15, gy, x0 + card_w - 15, gy], fill=(*accent_color, 120), width=2)

        # Character sprite
        sprite_size = (int(512 * scale), int(512 * scale))
        resized = img.resize(sprite_size, Image.LANCZOS)
        px = x0 + (card_w - sprite_size[0]) // 2
        sheet.paste(resized, (px, sprite_y), resized)

        # Labels
        ty = y0 + sprite_h + 20
        draw.text((x0 + 15, ty), f"0{idx+1}  {name}", fill=(*accent_color, 255))
        draw.text((x0 + 15, ty + 25), intent, fill=(180, 190, 220, 255))
        draw.text((x0 + 15, ty + 48), quote, fill=(130, 140, 175, 255))

        # State tag
        draw.rounded_rectangle([x0 + card_w - 120, ty, x0 + card_w - 10, ty + 22],
                                radius=6, fill=(*accent_color, 60))
        draw.text((x0 + card_w - 115, ty + 3), "STANDALONE ✓", fill=(*accent_color, 255))

    return sheet


def main():
    print("=" * 70)
    print("PHASE C/D — PROCESSING GENERATED SPECIAL PERFORMANCE ILLUSTRATIONS")
    print("=" * 70)

    # Record baseline hashes of core states (immutability check)
    core_dir = Path("assets/meli/character/states")
    core_hashes_before = {
        f.name: hashlib.sha256(f.read_bytes()).hexdigest()
        for f in sorted(core_dir.glob("*.png"))
    }
    print(f"\n[Phase B] Locked {len(core_hashes_before)} core state hashes.")

    results = {}
    grounding = {"proximity": 494, "hover": 494, "click_pet": 494, "celebration": 491}

    for state, pattern in GENERATION_MAP.items():
        src = find_latest(pattern)
        if src is None:
            print(f"\n[FAIL] No generated file found for {state} (pattern: {pattern})")
            return False
        
        out_path = Path(f"assets/meli/character/special/meli_{state}.png")
        result = process_generated(state, src, out_path, grounding_y=grounding[state])
        results[state] = result

    # Sync to public/
    pub_dir = Path("public/special")
    pub_dir.mkdir(parents=True, exist_ok=True)
    for state, img in results.items():
        pub_path = pub_dir / f"meli_{state}.png"
        img.save(pub_path, "PNG")
        print(f"  [SYNC] public/special/meli_{state}.png")
        # Root-level fallbacks
        img.save(f"public/{state}.png", "PNG")

    print("\n" + "-" * 70)
    print("[Phase D] CREATING PROXIMITY vs HOVER QA REVIEW SHEET")

    prox_hover_review = create_proximity_hover_review(results["proximity"], results["hover"])
    qa_dir = Path("assets/meli/qa")
    qa_dir.mkdir(parents=True, exist_ok=True)
    review_path = qa_dir / "special_proximity_hover_review.png"
    prox_hover_review.save(review_path, "PNG")
    
    # Also sync to design/qa/
    Path("design/qa").mkdir(parents=True, exist_ok=True)
    prox_hover_review.save("design/qa/special_proximity_hover_review.png", "PNG")
    print(f"  [SAVED] {review_path}")

    # Pairwise MAD matrix
    print("\n[Phase D] PAIRWISE DISTINCTNESS MATRIX:")
    all_names = list(results.keys())
    for i in range(len(all_names)):
        for j in range(i+1, len(all_names)):
            a = np.array(results[all_names[i]]).astype(float)
            b = np.array(results[all_names[j]]).astype(float)
            mad = float(np.mean(np.abs(a - b)))
            status = "PASS" if mad >= 3.5 else "FAIL"
            print(f"  [{status}] {all_names[i]} vs {all_names[j]}: MAD = {mad:.2f}")

    # CRITICAL: Verify core states are untouched
    print("\n[Phase B] VERIFYING CORE STATE IMMUTABILITY:")
    all_ok = True
    for name, old_hash in core_hashes_before.items():
        new_hash = hashlib.sha256((core_dir / name).read_bytes()).hexdigest()
        status = "PASS" if old_hash == new_hash else "FAIL"
        if status == "FAIL":
            all_ok = False
        print(f"  [{status}] {name}: SHA={old_hash[:12]}")

    if not all_ok:
        print("[CRITICAL FAIL] Core state hashes changed!")
        return False
    
    print("\n[SUCCESS] All core states remain byte-for-byte identical.")
    print("=" * 70)
    print("PHASE C/D COMPLETE — PROXIMITY, HOVER, CLICK_PET, CELEBRATION rebuilt.")
    print("Review sheet available at assets/meli/qa/special_proximity_hover_review.png")
    print("=" * 70)
    return True


